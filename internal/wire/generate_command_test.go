// TestValidateGenerateCommand covers Go generate tokenization and invalid directive input.
func TestValidateGenerateCommand(t *testing.T) {
	for _, command := range []string{"", "go tool wire", "\tgo\ttool wire  ", `"/path with spaces/wire"`, `go tool wire ""`, `$WIRE_GO tool wire`} {
		t.Run(command, func(t *testing.T) {
			if err := validateGenerateCommand(command); err != nil {
				t.Fatalf("validateGenerateCommand(%q): %v", command, err)
			}
		})
	}
	for _, command := range []string{" \t ", "go\nwire", "go\rwire", "go\x00wire", string([]byte{0xff}), `"unterminated`, `"bad\q"`, `"wire"gen`, `"" gen`, `go "\x00"`} {
		t.Run(command, func(t *testing.T) {
			if err := validateGenerateCommand(command); err == nil {
				t.Fatalf("validateGenerateCommand(%q) succeeded", command)
			}
		})
	}
}

// TestGenerateRejectsInvalidCommand verifies validation precedes loading packages or cached output.
func TestGenerateRejectsInvalidCommand(t *testing.T) {
	results, errs := Generate(context.Background(), t.TempDir(), nil, []string{"."}, &GenerateOptions{GenerateCommand: "go\nwire"})
	if len(results) != 0 || len(errs) != 1 || !strings.Contains(errs[0].Error(), "generate_command") {
		t.Fatalf("Generate returned %v, %v", results, errs)
	}
}

// TestFrameGenerateCommand preserves default output and makes overrides repeatable.
func TestFrameGenerateCommand(t *testing.T) {
	for _, test := range []struct {
		name, tags, command, want string
	}{
		{"default", "", "", "go run -mod=mod github.com/goforj/wire/cmd/wire"},
		{"default tags", "fixture,other", "", `go run -mod=mod github.com/goforj/wire/cmd/wire gen -tags "fixture,other"`},
		{"tool", "", "go tool wire", `go tool wire gen -generate_command "go tool wire"`},
		{"tool tags", "fixture,other", "go tool wire", `go tool wire gen -generate_command "go tool wire" -tags "fixture,other"`},
		{"environment", "", "$WIRE_GO tool wire", `$WIRE_GO tool wire gen -generate_command "${DOLLAR}WIRE_GO tool wire"`},
		{"quoted executable", "", `"/path with spaces/wire"`, `"/path with spaces/wire" gen -generate_command "\"/path with spaces/wire\""`},
	} {
		t.Run(test.name, func(t *testing.T) {
			g := newGen(&packages.Package{Name: "fixture"})
			g.buf.WriteString("func Initialize() {}\n")
			got := string(g.frame(test.tags, test.command))
			want := "// Code generated by Wire. DO NOT EDIT.\n\n//go:generate " + test.want + "\n//+build !wireinject\n\npackage fixture\n\nfunc Initialize() {}\n"
			if got != want {
				t.Fatalf("frame output = %q, want %q", got, want)
			}
		})
	}
	if got := newGen(&packages.Package{Name: "fixture"}).frame("", "go tool wire"); got != nil {
		t.Fatalf("empty generator produced %q", got)
	}
}

// TestOutputCacheKeySeparatesGenerateCommands prevents one command's header leaking into another.
func TestOutputCacheKeySeparatesGenerateCommands(t *testing.T) {
	root := &packages.Package{PkgPath: "example.com/fixture"}
	keys := make(map[string]string)
	wd := t.TempDir()
	for _, command := range []string{"", "go tool wire", "$WIRE_GO tool wire"} {
		key, err := outputCacheKey(wd, &GenerateOptions{GenerateCommand: command}, root)
		if err != nil {
			t.Fatal(err)
		}
		if previous, exists := keys[key]; exists {
			t.Fatalf("commands %q and %q share output cache key", previous, command)
		}
		keys[key] = command
	}
}
